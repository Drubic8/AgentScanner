ENTRIES = {}
for _line in _ROWS.strip().splitlines():
    _codes, _page, _reason = _line.split('|', 2)
    for _code in _codes.split(','):
        ENTRIES[_code] = (_reason, int(_page))


def code_text(value):
    if type(value) is int:
        return str(value) if value >= 0 else None
    if isinstance(value, str):
        text = value.strip()
        if re.fullmatch(r'\d{1,8}', text):
            return str(int(text))
        if re.fullmatch(r'0[xX][0-9a-fA-F]{1,4}', text):
            return f'0x{int(text, 16):04x}'
    return None


def lookup(code):
    code = code_text(code)
    if code in ENTRIES:
        reason, page = ENTRIES[code]
        return reason, page
    if code is None or not code.isdecimal():
        return None
    if 280 <= int(code) <= 299:
        return ENTRIES['28X-29X']
    for pattern, (reason, page) in ENTRIES.items():
        if 'X' not in pattern or '-' in pattern:
            continue
        expression = pattern.replace('BBB', r'(?P<chip>\d{3})')
        # 90XX describes a process code, not two board indexes.
        expression = expression.replace('XX', r'\d{2}').replace('X', r'(?P<board>\d)')
        match = re.fullmatch(expression, code)
        if match:
            return reason.format(**match.groupdict()), page
    return None


def decode_errors(value):
    """Support RPC code->timestamp maps, arrays and scalar codes; retain reasons."""
    found = {}
    def add(raw, reason=None):
        code = code_text(raw)
        if code is None or code in ('0', '0x0000'):
            return
        reasons = found.setdefault(code, [])
        if isinstance(reason, str) and reason.strip() and reason.strip() not in reasons:
            reasons.append(reason.strip())

    def visit(item):
        if isinstance(item, list):
            for child in item:
                visit(child)
        elif isinstance(item, dict):
            reason = item.get('reason')
            if 'code' in item:
                add(item['code'], reason)
            for key in item:
                add(key, reason)
        else:
            add(item)

    visit(value)
    descriptions = []
    for code, reasons in found.items():
        entry = lookup(code)
        text = f'Код {code} — ' + (entry[0] if entry else 'нет расшифровки в справочнике 03.06.2026')
        for reason in reasons:
            text += '\nСообщение устройства: ' + reason
        if entry:
            text += f'\n{SOURCE}, стр. {entry[1]}'
        descriptions.append(text)
    return '-'.join(found), '\n\n'.join(descriptions)


