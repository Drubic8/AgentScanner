class RpcTransport:
    def __init__(self, fixture):
        self.info = deepcopy(fixture["rpc_info"])
        self.pools = deepcopy(fixture["rpc_pools"])
        self.setting = {"code": 0, "desc": "get.miner.setting", "msg": {"btrom-worker-suffix": "", "power-limit": 3000}}
        self.calls, self.setters, self.connections = [], [], []
        self.reply = {"code": 0, "desc": "set.miner.pools", "msg": "ok"}
        self.setter_error = None

    def rpc(self, command, parameter=None):
        packet = {"cmd": command}
        if parameter is not None:
            packet["param"] = parameter
        return self.rpc_packet(None, packet)

    @contextmanager
    def connection(self, port):
        self.connections.append(port)
        yield object()

    def rpc_packet(self, sock, packet):
        self.calls.append(deepcopy(packet))
        command = packet["cmd"]
        if command == "get.device.info":
            return deepcopy(self.info)
        if command == "get.miner.status" and packet.get("param") == "pools":
            return deepcopy(self.pools)
        if command == "get.miner.setting":
            return deepcopy(self.setting)
        if command != "set.miner.pools":
            raise AssertionError("Unreviewed RPC operation")
        self.setters.append(deepcopy(packet))
        if self.setter_error:
            raise self.setter_error
        return deepcopy(self.reply)


class WhatsminerPoolBackendTests(unittest.TestCase):
    def setUp(self):
        self.fixture = json.loads(FIXTURE.read_text(encoding="utf-8"))
        self.record = record("MicroBT", "Stock", "M50_VH75")
        self.record.identity.profile_id = "microbt.rpc3"
        self.record.identity.api_version = "3.0.5"
        self.record.identity.firmware_version = "20260908.12.Rel2"
        self.credentials = Credentials("user2", "synthetic-api-password")
        self.service = SimpleNamespace(credentials_for=lambda ip: self.credentials)
        self.transport = RpcTransport(self.fixture)

    def read(self):
        return backend.read_state(self.service, self.record, self.transport)

    def complete_slots(self, state, passwords=("  pool:пароль,1  ", "***", "")):
        slots = deepcopy(state.slots)
        for slot, password in zip(slots, passwords):
            slot["pass"] = password
        return slots

    @unittest.skipUnless(CRYPTO_AVAILABLE, "cryptography is an optional pool-write dependency")
    def test_pkcs7_known_answer_from_independent_dotnet_aes_provider(self):
        # These fixed synthetic values were encoded separately with .NET's
        # SHA256 + Aes/ECB/PKCS7, not generated by the implementation under test.
        material = b"set.miner.poolssynthetic-api-passwordsynthetic-salt1700000000"
        key = hashlib.sha256(material).digest()
        self.assertEqual(key.hex(), "7ba2d5d55802f1bab58d8f1ef59bdeadd21cd2c95df77d99122558ef8751c186")
        self.assertEqual(base64.b64encode(key).decode()[:8], "e6LV1VgC")
        plaintext = b'[{"pool":"stratum+tcp://pool.invalid:3333","worker":"TEST.001","passwd":"x"}]'
        self.assertEqual(wm.encrypt_parameter(key, plaintext),
            "Vjt0Ud8S8swr4tyg3ekXPt/eIGm2AReKfoNgyyXY3yFO6NUQ6H0p4Ezr3XFzML8xxIQglKLw9CCXVrVfQomo4PGJnk6Y6gkdQO/jOH612Ho=")

    def test_runtime_passwords_are_never_treated_as_user_supplied(self):
        self.transport.pools["msg"]["pools"][0]["passwd"] = "do-not-copy-runtime-secret"
        state = self.read()
        self.assertEqual(state.backend_id, wm.BACKEND_ID)
        self.assertEqual(state.opaque["verification_kind"], "runtime_without_passwords")
        self.assertTrue(all(set(slot) == {"url", "user"} for slot in state.slots))
        with self.assertRaises(backend.PoolBackendError):
            backend.validate_state(state, state.slots)
        self.assertNotIn("synthetic-api-password", repr(state))
        self.assertNotIn("do-not-copy-runtime-secret", repr(state))
        self.assertFalse(self.transport.setters)

    def test_all_three_explicit_password_strings_are_required_without_defaults(self):
        state = self.read()
        entered = self.complete_slots(state)
        parameters = wm.payload(entered)
        self.assertEqual([pool["passwd"] for pool in parameters], ["  pool:пароль,1  ", "***", ""])
        for index in range(3):
            missing = deepcopy(entered)
            missing[index].pop("pass")
            with self.subTest(index=index), self.assertRaises(backend.PoolBackendError):
                wm.payload(missing)
        self.assertTrue(all("pass" not in slot for slot in state.slots))

    def test_read_state_does_not_require_api_credentials_but_ready_validation_does(self):
        self.credentials = None
        state = self.read()
        self.assertEqual(len(state.slots), 3)
        # Missing pool values take precedence over API authentication readiness.
        with self.assertRaises(backend.PoolBackendError) as missing:
            backend.validate_state(state, state.slots)
        self.assertEqual(missing.exception.status, "unsupported")
        with self.assertRaises(backend.PoolBackendError) as auth:
            backend.validate_state(state, self.complete_slots(state))
        self.assertEqual(auth.exception.status, "auth_required")
        self.assertFalse(self.transport.setters)

    @unittest.skipUnless(CRYPTO_AVAILABLE, "cryptography is an optional pool-write dependency")
    def test_one_array_serialization_exact_passwords_fresh_salt_and_configured_account(self):
        from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes
        state = self.read()
        entered = self.complete_slots(state)
        baseline = deepcopy(entered)
        self.transport.info["msg"]["salt"] = "synthetic-new-salt"
        with patch.object(wm.time, "time", return_value=1700000000):
            self.assertTrue(backend.write_state(self.service, self.record, self.transport, state, entered))
        self.assertEqual(self.transport.connections, [4433])
        self.assertEqual(len(self.transport.setters), 1)
        request = self.transport.setters[0]
        key = hashlib.sha256(b"set.miner.poolssynthetic-api-passwordsynthetic-new-salt1700000000").digest()
        self.assertEqual(request["account"], "user2")
        self.assertEqual(request["token"], base64.b64encode(key).decode()[:8])
        self.assertEqual(request["ts"], 1700000000)
        self.assertEqual(set(request), {"cmd", "ts", "account", "token", "param"})
        decryptor = Cipher(algorithms.AES(key), modes.ECB()).decryptor()
        padded = decryptor.update(base64.b64decode(request["param"])) + decryptor.finalize()
        self.assertTrue(1 <= padded[-1] <= 16)
        self.assertEqual(padded[-padded[-1]:], bytes([padded[-1]]) * padded[-1])
        decoded = json.loads(padded[:-padded[-1]])
        self.assertIsInstance(decoded, list)  # No double JSON string wrapping.
        self.assertEqual(decoded, [{"pool": slot["url"], "worker": slot["user"], "passwd": slot["pass"]} for slot in entered])
        self.assertEqual(entered, baseline)
        self.assertEqual([packet["cmd"] for packet in self.transport.calls[-4:]],
                         ["get.device.info", "get.miner.status", "get.miner.setting", "set.miner.pools"])

    def test_signature_ignores_runtime_metrics_and_ephemeral_auth_but_tracks_pool_and_suffix(self):
        first = self.read()
        self.transport.info["msg"]["salt"] = "different-salt"
        self.transport.pools["when"] += 100
        self.transport.pools["msg"]["pools"][0].update({"last-share-time": 1800000000, "status": "dead", "reject-percent": 25})
        self.transport.setting["msg"]["power-limit"] = 4500
        second = self.read()
        self.assertEqual(backend.state_signature(first), backend.state_signature(second))
        self.assertTrue(backend.equivalent_state(first, second))
        self.transport.pools["msg"]["pools"][0]["account"] = "another.worker"
        third = self.read()
        self.assertNotEqual(backend.state_signature(first), backend.state_signature(third))
        self.assertTrue(backend.equivalent_state(first, third, ignore_pools=True))
        self.transport.setting["msg"]["btrom-worker-suffix"] = "_AUTO"
        fourth = self.read()
        self.assertFalse(backend.equivalent_state(first, fourth, ignore_pools=True))

    def test_missing_crypto_is_lazy_and_becomes_safe_unsupported_before_opening_socket(self):
        original_import = __import__
        def import_without_crypto(name, *args, **kwargs):
            if name.startswith("cryptography"):
                raise ImportError("synthetic dependency absence")
            return original_import(name, *args, **kwargs)
        with patch("builtins.__import__", side_effect=import_without_crypto):
            state = self.read()
            with self.assertRaises(backend.PoolBackendError) as problem:
                backend.validate_state(state, self.complete_slots(state))
            self.assertEqual(problem.exception.status, "unsupported")
            self.assertIn("cryptography", str(problem.exception))
            with self.assertRaises(backend.PoolBackendError):
                backend.write_state(self.service, self.record, self.transport, state, self.complete_slots(state))
        self.assertFalse(self.transport.connections)
        self.assertFalse(self.transport.setters)

    def test_fresh_read_requires_rpc3_identity_write_switch_salt_and_all_ordered_pool_ids(self):
        for change in ("disabled", "bool_switch", "salt", "model", "firmware", "api", "ids", "duplicate", "short", "bool_id"):
            with self.subTest(change=change):
                self.transport = RpcTransport(self.fixture)
                if change == "disabled": self.transport.info["msg"]["system"]["apiswitch"] = "0"
                elif change == "bool_switch": self.transport.info["msg"]["system"]["apiswitch"] = True
                elif change == "salt": self.transport.info["msg"]["salt"] = ""
                elif change == "model": self.transport.info["msg"]["miner"]["type"] = "different-model"
                elif change == "firmware": self.transport.info["msg"]["system"]["fwversion"] = "another-build"
                elif change == "api": self.transport.info["msg"]["system"]["api"] = "3.0.4"
                elif change == "ids": self.transport.pools["msg"]["pools"].reverse()
                elif change == "duplicate": self.transport.pools["msg"]["pools"][1]["id"] = 1
                elif change == "short": self.transport.pools["msg"]["pools"].pop()
                else: self.transport.pools["msg"]["pools"][0]["id"] = True
                with self.assertRaises(backend.PoolBackendError): self.read()
                self.assertFalse(self.transport.setters)

