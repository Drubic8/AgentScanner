    @unittest.skipUnless(CRYPTO_AVAILABLE, "cryptography is an optional pool-write dependency")
    def test_explicit_error_or_malformed_ack_and_timeout_never_repeat_the_setter(self):
        replies = [({"code": 0, "desc": wm.COMMAND}, True), ({"code": -1, "desc": wm.COMMAND}, False),
                   ({"code": -4, "desc": wm.COMMAND}, False), ({"code": 0, "desc": "other.command"}, None),
                   ({"code": False, "desc": wm.COMMAND}, None), ({"code": 0.0, "desc": wm.COMMAND}, None),
                   ({"code": "0", "desc": wm.COMMAND}, None), ({}, None), ([], None)]
        for reply, expected in replies:
            with self.subTest(reply_type=type(reply).__name__, expected=expected):
                self.transport = RpcTransport(self.fixture)
                self.transport.reply = reply
                state = self.read()
                self.assertIs(backend.write_state(self.service, self.record, self.transport, state, self.complete_slots(state)), expected)
                self.assertEqual(len(self.transport.setters), 1)
        for failure in (requests.ReadTimeout("PRIVATE-ERROR"), OSError("PRIVATE-ERROR"), ProtocolError("PRIVATE-ERROR")):
            with self.subTest(failure=type(failure).__name__):
                self.transport = RpcTransport(self.fixture)
                self.transport.setter_error = failure
                state = self.read()
                self.assertIsNone(backend.write_state(self.service, self.record, self.transport, state, self.complete_slots(state)))
                self.assertEqual(len(self.transport.setters), 1)

    def test_secret_values_stay_out_of_repr_and_exported_evidence(self):
        self.transport.info["msg"]["salt"] = "PRIVATE-SALT"
        state = self.read()
        self.assertNotIn("PRIVATE-SALT", repr(state))
        report = evidence_from_state(state, self.record)
        for secret in ("PRIVATE-SALT", "synthetic-api-password", "SYNTHETIC.pool1", "synthetic-primary.example.invalid"):
            self.assertNotIn(secret, json.dumps(report))


