    @unittest.skipUnless(CRYPTO_AVAILABLE, "cryptography is an optional pool-write dependency")
    def test_fresh_known_mac_or_serial_change_or_disappearance_blocks_same_model_write(self):
        self.record.identity.serial = "synthetic-known-serial"
        self.record.identity.mac = "02:AB:CD:EF:22:33"
        for change in ("serial", "mac", "missing_serial", "missing_mac"):
            with self.subTest(change=change):
                self.transport = RpcTransport(self.fixture)
                system = self.transport.info["msg"]["system"]
                system.update({"serial": "synthetic-known-serial", "mac": "02:ab:cd:ef:22:33"})
                state = self.read()
                if change.startswith("missing_"):
                    system.pop(change.removeprefix("missing_"))
                elif change == "serial":
                    system["serial"] = "different-serial"
                else:
                    system["mac"] = "02:ab:cd:ef:22:44"
                with self.assertRaises(backend.PoolBackendError) as problem:
                    backend.write_state(self.service, self.record, self.transport, state, self.complete_slots(state))
                self.assertEqual(problem.exception.status, "changed")
                self.assertNotIn("different-serial", str(problem.exception))
                self.assertFalse(self.transport.setters)

